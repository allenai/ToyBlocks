"""Helpers used by ``scripts/evaluate.py`` to keep ``_run_eval`` legible.

Responsibilities:

- ``setup_queue``: construct an :class:`EpisodeQueueClient` and attach it
  to the env as ``base_env.queue_client``, install the phantom-episode
  filter on ``RecordEpisode``, and bump per-fetch debug logging on the
  episode-queue logger. Returns ``None`` when ``--queue_url`` is unset.
"""

from __future__ import annotations

import importlib.util
import json
import logging
from collections.abc import Sequence
from pathlib import Path
from typing import Any, Optional

logger = logging.getLogger(__name__)


def _load_task_profiles(task: str) -> Optional[dict]:
    """Load a task's generated ``profiles.json``, refusing stale packages.

    Returns ``None`` when ``task`` is not an autogen package (no importable
    package for its entry point, or no ``profiles.json`` beside it) -- those
    carry no cube-scale slot constraint.

    Raises when the package's ``codegen_version`` does not match this checkout's
    :data:`~blocksuite.tamp.blocks.template.codegen.AUTOGEN_PACKAGE_VERSION`.
    Autogen dirs are gitignored, so a package left over from an older codegen
    looks exactly like a fresh one while keeping its own goal selection, success
    gate and cube-scale slots -- differences that move success rates instead of
    failing. Validating here means no caller can read ``profiles.json`` without
    the check.
    """
    import gymnasium as gym

    # Cheap: codegen's own blocksuite/Isaac imports are all function-local.
    from blocksuite.tamp.blocks.template.codegen import AUTOGEN_PACKAGE_VERSION

    entry_point = gym.spec(task).entry_point
    if not isinstance(entry_point, str):
        return None
    # entry_point is "<pkg>.env:<Class>"; profiles.json sits in <pkg>.
    package_name = entry_point.split(":", 1)[0].rsplit(".", 1)[0]
    spec = importlib.util.find_spec(package_name)
    if spec is None or spec.origin is None:
        return None
    profiles_path = Path(spec.origin).parent / "profiles.json"
    if not profiles_path.exists():
        return None

    profiles = json.loads(profiles_path.read_text())
    version = profiles.get("codegen_version")
    if version != AUTOGEN_PACKAGE_VERSION:
        raise RuntimeError(
            f"{profiles_path} was generated by codegen version {version!r}, but "
            f"this checkout generates version {AUTOGEN_PACKAGE_VERSION}. The "
            "package on disk keeps its own goal selection, success gate and "
            "cube-scale slots, so it would report different numbers for the same "
            f"policy without failing. Regenerate {task} with "
            "generate_task_from_dataset.py (or generate_task_from_pddl.py)."
        )
    return profiles


def allocate_env_slots(
    slot_counts: Sequence[int], slot_work: Sequence[float], num_envs: int
) -> list[int]:
    """Spawn slot for each of ``num_envs`` envs, sized to each slot's queued workload.

    Block size is fixed per env at spawn, so a cube-scale slot's episodes can only
    run on that slot's envs and the slowest slot sets the wall time. Every slot
    with queued episodes gets one env; each further env goes to the slot whose
    queue takes longest per env (``slot_work`` / envs, e.g. summed expert frames),
    never past one env per episode. Envs left once every episode has its own are
    spread round-robin (they idle). Slots are interleaved over the env grid.
    """
    active = [s for s, n in enumerate(slot_counts) if n > 0]
    if num_envs < len(active):
        raise ValueError(
            f"{num_envs} envs cannot cover the {len(active)} cube-scale slots with "
            "queued episodes; each needs at least one env spawned at its size."
        )
    envs = {s: 1 for s in active}
    for _ in range(num_envs - len(active)):
        open_slots = [s for s in active if envs[s] < slot_counts[s]]
        if not open_slots:
            break
        busiest = max(open_slots, key=lambda s: (slot_work[s] / envs[s], slot_counts[s]))
        envs[busiest] += 1
    for k in range(num_envs - sum(envs.values())):
        envs[active[k % len(active)]] += 1
    order: list[int] = []
    while len(order) < num_envs:
        for s in active:
            if envs[s] > 0:
                order.append(s)
                envs[s] -= 1
    return order


def _queue_slot_stats(queue_url: str) -> tuple[list[int], list[float]] | None:
    """Per-slot queued episode counts and expert frames from the queue's ``/size``.

    ``None`` when the queue does not report them (older queue server, or no
    cube-scale routing).
    """
    import requests

    size_url = queue_url.rsplit("/", 1)[0] + "/size"
    status = requests.get(size_url, timeout=30).json()
    counts = status.get("slot_counts")
    work = status.get("slot_expert_frames")
    if not counts or work is None or len(work) != len(counts):
        return None
    return [int(c) for c in counts], [float(w) for w in work]


def reconcile_num_envs_with_task(args: Any) -> None:
    """Snap ``args.num_envs`` to a value the task's generated env will accept.

    Autogen block envs bake ``MAX_NON_SIM_STATE_RANDOMIZATIONS`` cube-scale spawn
    slots (recorded in the task package's ``profiles.json`` as ``num_profiles``).
    Isaac can't reconfigure these non-sim-state randomizations at runtime, so the
    generated ``_setup_scene_objects`` asserts ``num_envs`` is a positive multiple
    of that count (mandatory when block scale is derived from recorded per-episode
    sizes; below one full set is also allowed otherwise).

    Queue-driven launchers right-size ``num_envs`` from queue depth without knowing
    the slot count, so this reconciles that boundary value before the env is built
    (mirrors :func:`reconcile_env_cfg_with_dataset`). When the queue reports its
    per-slot workload (``/size``), the slot of every env is chosen instead
    (``env_cfg.env_slots``, :func:`allocate_env_slots`) and ``num_envs`` need not
    be a multiple. Tasks whose package carries no ``profiles.json`` have no such
    constraint and are left untouched; a package from an older codegen raises (see
    :func:`_load_task_profiles`).
    """
    profiles = _load_task_profiles(args.task)
    if profiles is None:
        return

    num_slots = int(profiles["num_profiles"])
    derive = bool(profiles["derive_block_scale_from_size"])
    requested = int(args.num_envs)

    # Queue-driven exact-size eval: size each slot's env count to its queued
    # workload instead of num_envs / num_slots each (see allocate_env_slots). Replay
    # too: a queue of one cube scale then needs only the one env replay supports.
    queue_url = getattr(args, "queue_url", None)
    stats = _queue_slot_stats(queue_url) if derive and queue_url else None
    if stats is not None and len(stats[0]) == num_slots and sum(stats[0]) > 0:
        counts, work = stats
        num_envs = max(requested, sum(1 for c in counts if c > 0))
        env_slots = allocate_env_slots(counts, work, num_envs)
        args.num_envs = num_envs
        args.env_cfg.env_slots = tuple(env_slots)
        per_slot = [env_slots.count(s) for s in range(num_slots)]
        logger.info(
            "[num_envs] %d envs over %d cube-scale slots by queued workload: envs per "
            "slot %s for episodes per slot %s",
            num_envs, num_slots, per_slot, counts,
        )
        return

    if derive:
        # Exact per-episode matching needs every slot spawned: floor to a multiple,
        # never below one full set (which would drop slots and fail the assertion).
        reconciled = max(num_slots, (requested // num_slots) * num_slots)
    elif requested < num_slots:
        reconciled = requested
    else:
        reconciled = (requested // num_slots) * num_slots

    if reconciled != requested:
        # Rounding up is the surprising direction: it costs GPU memory the caller
        # did not ask for, and is unavoidable because one full set of spawn slots
        # must exist. Warn so `--num_envs 2` on an 8-slot task is visible in the log
        # rather than showing up as an unexplained 4x memory footprint.
        log = logger.warning if reconciled > requested else logger.info
        log(
            "[num_envs] reconciled %d -> %d for task %s (%d cube-scale slots, "
            "derive_block_scale_from_size=%s)%s",
            requested,
            reconciled,
            args.task,
            num_slots,
            derive,
            " -- raised to spawn one full set of slots" if reconciled > requested else "",
        )
        args.num_envs = reconciled


def setup_queue(args: Any, env: Any, base_env: Any, prompt_resolver: Any) -> Optional[Any]:
    """Construct the :class:`EpisodeQueueClient` and attach it to the env.

    Returns ``None`` when ``--queue_url`` is not set. Otherwise returns the
    constructed client (for the eval loop's ``done`` / ``previous_setups``
    accesses) after:

    - bumping the ``blocksuite.utils.episode_queue`` logger to ``DEBUG`` so
      every fetch / write / verify diff is visible (search for
      ``# VERBOSE-QUEUE``), but only when ``--verify_scene`` is set so the core
      path stays quiet;
    - assigning ``base_env.queue_client`` so the first ``env.reset()`` and
      every auto-reset ``_reset_idx`` consume from the queue;
    - installing ``should_save_episode`` / ``should_save_in_flight_episode``
      callbacks on the ``RecordEpisode`` and ``RecordMetrics`` wrappers to
      discard "phantom" episodes (sub-envs that ran with no queue setup
      because the queue drained before their reset).
    """
    if not args.queue_url:
        return None

    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s %(levelname)s %(name)s: %(message)s",
    )
    # Verbose per-fetch/write/verify queue logging is only useful when
    # inspecting scene reconstruction; keep the core eval path quiet otherwise.
    if getattr(args, "verify_scene", False) or getattr(args, "verify_scene_strict", False):
        logging.getLogger("blocksuite.utils.episode_queue").setLevel(logging.DEBUG)

    from blocksuite.utils.episode_queue import EpisodeQueueClient
    from blocksuite.wrappers.record_episode import RecordEpisode
    from blocksuite.wrappers.record_metrics import RecordMetrics

    # Number of cube-scale spawn slots baked by codegen (env i spawns at slot
    # base_env.env_slots[i], round-robin by default); the client passes that slot
    # so the queue serves only size-matched episodes. Defaults to 1 for envs
    # without the attribute.
    num_slots = int(getattr(base_env, "MAX_NON_SIM_STATE_RANDOMIZATIONS", 1) or 1)
    # The scale each slot is spawned at, in slot order. Empty for tasks with no
    # per-episode size matching (where MAX_NON_SIM_STATE_RANDOMIZATIONS is the
    # legacy fixed randomization-profile count and means nothing about scale), so
    # the queue's ordering cross-check keys off the real signal.
    randomizations = getattr(base_env, "randomizations", None)
    slot_scales = (
        list(randomizations.get("cube_scale_slots") or [])
        if isinstance(randomizations, dict)
        else []
    )
    queue_client = EpisodeQueueClient(
        base_env=base_env,
        queue_url=args.queue_url,
        num_envs=args.num_envs,
        num_slots=num_slots,
        slot_scales=slot_scales,
        env_slots=getattr(base_env, "env_slots", None),
        on_setups_changed=prompt_resolver.update_setups,
        # Dataset replay restores the recorded frame-0 arm joint velocity so the
        # first stepped action sees the recorded motion; policy evals keep the
        # at-rest start.
        apply_recorded_joint_velocity=bool(getattr(args, "replay", False)),
        # Policy evals start with the gripper open; replay plays the recording back
        # from its own frame-0 gripper.
        start_gripper_open=not bool(getattr(args, "replay", False)),
    )
    base_env.queue_client = queue_client

    # A finished episode is real iff its env held a setup while it ran, which by
    # flush time lives in previous_setups (the auto-reset fetch has already moved
    # current -> previous). An episode still in flight when the rollout ends is
    # the current one, so that path keys off current_setups instead.
    for wrapper_cls in (RecordEpisode, RecordMetrics):
        recorder: Any = env
        while recorder is not None and not isinstance(recorder, wrapper_cls):
            recorder = getattr(recorder, "env", None)
        if recorder is None:
            logger.warning(
                "%s wrapper not found in the env chain; phantom-episode filters "
                "will not be installed — phantom episodes may be saved to disk.",
                wrapper_cls.__name__,
            )
            continue
        recorder.should_save_episode = (
            lambda i: queue_client.previous_setups[i] is not None
        )
        recorder.should_save_in_flight_episode = (
            lambda i: queue_client.current_setups[i] is not None
        )
    return queue_client
